# # resize_utils.py — 웨이퍼 맵 리사이즈 (공용 모듈)
#
# ## 왜 일반적인 이미지 리사이즈(bilinear/bicubic)를 쓰면 안 되는가
#
# 사진을 리사이즈할 때 흔히 쓰는 bilinear(양선형) 보간은 주변 픽셀 값을
# **섞어서** 중간값을 만들어낸다. 사진에서는 이게 자연스럽다 — 밝기 128과
# 130 사이는 129라는 밝기가 실제로 존재할 수 있으니까.
#
# 하지만 웨이퍼 맵의 픽셀 값 0/1/2는 밝기가 아니라 **서로 다른 범주(카테고리)**다.
# 0=다이 없음, 1=정상 다이, 2=불량 다이. 이웃한 0과 2를 섞어 "1.3"을 만들어봤자
# 그런 상태는 실제로 존재하지 않는다 — 오히려 정상(1)과 헷갈리는 가짜 값이 되어
# CNN 학습에 잡음만 더한다.
#
# 그래서 여기서는 **최근접 이웃(nearest neighbor)** 방식을 쓴다: 목표 위치에
# 가장 가까운 원본 픽셀의 값을 보간 없이 그대로 가져온다. 세그멘테이션/라벨
# 맵을 리사이즈할 때 흔히 쓰는 표준적인 방법이다.

# %%
import numpy as np


def resize_nearest(wafer_map: np.ndarray, target_size: int = 64) -> np.ndarray:
    """
    wafer_map(임의의 세로x가로 크기)을 (target_size, target_size)로
    최근접 이웃 방식으로 리사이즈한다. 원본에 없던 값은 절대 생기지 않는다.
    """
    h, w = wafer_map.shape

    # -----------------------------------------------------------
    # 문법 설명: np.arange와 팬시 인덱싱(fancy indexing)
    # -----------------------------------------------------------
    # np.arange(64)는 [0, 1, 2, ..., 63]을 만든다.
    # 이걸 원본 크기(h 또는 w) 비율로 늘리고 정수로 내림(astype(int))하면,
    # "목표의 i번째 칸은 원본의 몇 번째 칸에 대응하는가"를 알 수 있다.
    # 예: 원본 32칸 -> 목표 64칸이면 목표 0,1,2,3칸은 각각 원본 0,0,1,1칸에 대응.
    #
    # arr[idx_배열]처럼 배열을 인덱스로 넣어 한 번에 재배열하는 것을
    # "팬시 인덱싱"이라 한다. arr[row_idx][:, col_idx]는 먼저 행을,
    # 그다음 열을 이 방식으로 골라낸다.
    # -----------------------------------------------------------
    row_idx = (np.arange(target_size) * h / target_size).astype(int)
    col_idx = (np.arange(target_size) * w / target_size).astype(int)

    return wafer_map[row_idx][:, col_idx]
